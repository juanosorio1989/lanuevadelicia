/**
 * Imports the approved photos from assets-inbox/ (read only) into public/images/
 * and regenerates src/data/photos.ts. Run: npm run photos. Idempotent.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { entries } from "./photo-manifest";

const root = path.resolve(__dirname, "..");
const inbox = path.join(root, "assets-inbox");
const publicDir = path.join(root, "public");
const MAX = 2400;

async function main() {
  if (!fs.existsSync(inbox)) throw new Error("assets-inbox/ not found");
  const out: unknown[] = [];

  for (const e of entries) {
    const src = path.join(inbox, e.source);
    if (!fs.existsSync(src)) throw new Error(`Missing source: ${e.source}`);
    const slug = e.id.split("/")[1];
    const isLogo = e.id === "brand/logo";
    const rel = `/images/${e.group}/${slug}.${isLogo ? "png" : "jpg"}`;
    const dest = path.join(publicDir, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });

    const base = sharp(src).rotate();
    const pipeline = isLogo
      ? base.resize(1024, 1024, { fit: "inside", withoutEnlargement: true }).png()
      : base
          .resize(MAX, MAX, { fit: "inside", withoutEnlargement: true })
          .jpeg({ quality: 82, mozjpeg: true });
    const info = await pipeline.toFile(dest);
    out.push({ id: e.id, src: rel, width: info.width, height: info.height, alt: e.alt, group: e.group });
    console.log(`${e.id}  ${info.width}x${info.height}`);
  }

  // Favicon and app icons: the white logo on green-900.
  const logo = path.join(inbox, "logo.png");
  const logoPng = (size: number) =>
    sharp(logo)
      .resize(Math.round(size * 0.8), Math.round(size * 0.8), { fit: "inside" })
      .png()
      .toBuffer();
  const makeIcon = async (size: number, file: string) =>
    sharp({ create: { width: size, height: size, channels: 3, background: "#253D30" } })
      .composite([{ input: await logoPng(size), gravity: "center" }])
      .png()
      .toFile(file);
  await makeIcon(512, path.join(root, "src/app/icon.png"));
  await makeIcon(180, path.join(root, "src/app/apple-icon.png"));
  // favicon.ico: a PNG-encoded single-size ICO (32x32).
  const png32 = await sharp({ create: { width: 32, height: 32, channels: 3, background: "#253D30" } })
    .composite([{ input: await logoPng(32), gravity: "center" }])
    .png()
    .toBuffer();
  const header = Buffer.alloc(22);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(1, 4); // image count
  header.writeUInt8(32, 6); // width
  header.writeUInt8(32, 7); // height
  header.writeUInt16LE(1, 10); // planes
  header.writeUInt16LE(32, 12); // bits per pixel
  header.writeUInt32LE(png32.length, 14); // image size
  header.writeUInt32LE(22, 18); // image offset
  fs.writeFileSync(path.join(publicDir, "favicon.ico"), Buffer.concat([header, png32]));

  // Open Graph image: 1200x630 crop of the committed bandeja paisa master (works without assets-inbox).
  const ogSrc = path.join(publicDir, "images/dishes/bandeja-paisa.jpg");
  fs.mkdirSync(path.join(publicDir, "og"), { recursive: true });
  await sharp(ogSrc)
    .resize(1200, 630, { fit: "cover", position: "attention" })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(publicDir, "og/home.jpg"));
  console.log("og/home.jpg 1200x630");

  const body = JSON.stringify(out, null, 2);
  fs.writeFileSync(
    path.join(root, "src/data/photos.ts"),
    `import type { Photo } from "@/types/content";\n\n// Generated by scripts/import-photos.ts (npm run photos). Do not edit by hand.\nexport const photos: Photo[] = ${body};\n`,
  );
  console.log(`Wrote ${out.length} photos`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
